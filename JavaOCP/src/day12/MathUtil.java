package day12;

// 數學工具類
public class MathUtil {
	
	public static double add(double x, double y) { // 加
		return x + y;
	}
	
	public static double sub(double x, double y) { // 減
		return x - y;
	}
	
	public static double mul(double x, double y) { // 乘
		return x * y;
	}
	
	public static double div(double x, double y) { // 除
		return x / y;
	}
}
